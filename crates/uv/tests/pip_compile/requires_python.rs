use anyhow::Result;
use assert_fs::prelude::*;
use wiremock::matchers::{method, path};
use wiremock::{Mock, MockServer, ResponseTemplate};

use uv_static::EnvVars;
use uv_test::packse::WheelBuilder;
use uv_test::uv_snapshot;

/// Skip incompatible source archives before fetching metadata, including speculative prefetches.
#[tokio::test]
async fn requires_python_prefetch() -> Result<()> {
    let context = uv_test::test_context!("3.8");
    let (filename, wheel) = WheelBuilder::new(&"voluptuous".parse()?, &"0.14.2".parse()?).build();
    let server = MockServer::start().await;
    Mock::given(method("GET"))
        .and(path("/simple/voluptuous/"))
        .respond_with(ResponseTemplate::new(200).set_body_raw(
            format!(
                r#"<a href="/files/{filename}">{filename}</a>
<a href="/files/voluptuous-0.15.1.tar.gz" data-requires-python="&gt;=3.9">voluptuous-0.15.1.tar.gz</a>"#
            ),
            "text/html",
        ))
        .mount(&server)
        .await;
    Mock::given(method("GET"))
        .and(path(format!("/files/{filename}")))
        .respond_with(ResponseTemplate::new(200).set_body_bytes(wheel))
        .mount(&server)
        .await;
    Mock::given(path("/files/voluptuous-0.15.1.tar.gz"))
        .respond_with(ResponseTemplate::new(500))
        .expect(0)
        .named("Python-incompatible source archive")
        .mount(&server)
        .await;
    context
        .temp_dir
        .child("requirements.in")
        .write_str("voluptuous<=0.15.1")?;

    uv_snapshot!(context.pip_compile()
        .arg("requirements.in")
        .arg("--index-url")
        .arg(format!("{}/simple/", server.uri()))
        .env_remove(EnvVars::UV_EXCLUDE_NEWER), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in
    voluptuous==0.14.2
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");

    Ok(())
}

/// Serve wheels whose `Requires-Python` metadata is absent from the index page.
/// For example, PyTorch's networkx index has omitted `data-requires-python`:
/// <https://download.pytorch.org/whl/cpu/networkx/>.
async fn index_without_requires_python() -> Result<MockServer> {
    let server = MockServer::start().await;
    let mut links = Vec::new();
    for (version, requires_python) in [("3.2.1", ">=3.9"), ("3.3", ">=3.10")] {
        let (filename, wheel) = WheelBuilder::new(&"networkx".parse()?, &version.parse()?)
            .requires_python(Some(&requires_python.parse()?))
            .build();
        links.push(format!(r#"<a href="/files/{filename}">{filename}</a>"#));
        Mock::given(method("GET"))
            .and(path(format!("/files/{filename}")))
            .respond_with(ResponseTemplate::new(200).set_body_bytes(wheel))
            .mount(&server)
            .await;
    }
    Mock::given(method("GET"))
        .and(path("/networkx/"))
        .respond_with(ResponseTemplate::new(200).set_body_raw(links.join("\n"), "text/html"))
        .expect(1..)
        .mount(&server)
        .await;
    Ok(server)
}

/// Check that we honor `Requires-Python` when it is missing from the index page.
#[tokio::test]
async fn index_has_no_requires_python() -> Result<()> {
    let context = uv_test::test_context_with_versions!(&["3.9", "3.12"]);
    let server = index_without_requires_python().await?;

    let requirements_in = context.temp_dir.child("requirements.in");
    requirements_in.write_str("networkx")?;

    uv_snapshot!(context
        .pip_compile()
        .env_remove(EnvVars::UV_EXCLUDE_NEWER)
        .arg("--python")
        .arg("3.9")
        .arg("--index-url")
        .arg(server.uri())
        .arg("requirements.in"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] --python 3.9 requirements.in
    networkx==3.2.1
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");

    uv_snapshot!(context
        .pip_compile()
        .env_remove(EnvVars::UV_EXCLUDE_NEWER)
        .arg("--python")
        .arg("3.12")
        .arg("--index-url")
        .arg(server.uri())
        .arg("requirements.in"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] --python 3.12 requirements.in
    networkx==3.3
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");

    Ok(())
}

/// A universal resolution must revisit candidates after discovering their Python compatibility.
#[cfg(feature = "test-universal")]
#[tokio::test]
async fn index_has_no_requires_python_universal() -> Result<()> {
    let context = uv_test::test_context_with_versions!(&["3.9"]);
    let server = index_without_requires_python().await?;
    context
        .temp_dir
        .child("requirements.in")
        .write_str("networkx")?;

    // Add `ok` to prove that uv revisited `networkx==3.3` in the `>=3.10` fork.
    context.temp_dir.child("pyproject.toml").write_str(
        r#"
        [tool.uv]

        [[tool.uv.dependency-metadata]]
        name = "networkx"
        version = "3.2.1"
        requires-python = ">=3.9"

        [[tool.uv.dependency-metadata]]
        name = "networkx"
        version = "3.3"
        requires-python = ">=3.10"
        requires-dist = ["ok==1.0.0"]
        "#,
    )?;

    // The generated resolution should reflect the metadata above.
    uv_snapshot!(context
        .pip_compile()
        .env_remove(EnvVars::UV_EXCLUDE_NEWER)
        .arg("--python")
        .arg("3.9")
        .arg("--universal")
        .arg("--index-url")
        .arg(server.uri())
        .arg("--find-links")
        .arg(context.workspace_root.join("test").join("links"))
        .arg("requirements.in"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] --python 3.9 --universal requirements.in
    networkx==3.2.1 ; python_full_version < '3.10'
        # via -r requirements.in
    networkx==3.3 ; python_full_version >= '3.10'
        # via -r requirements.in
    ok==1.0.0 ; python_full_version >= '3.10'
        # via networkx

    ----- stderr -----
    Resolved 3 packages in [TIME]
    ");

    Ok(())
}
