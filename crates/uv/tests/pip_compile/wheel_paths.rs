//! Resolve local wheel path spellings and their transitive dependency metadata.

use anyhow::Result;
use assert_fs::prelude::*;

use uv_redacted::SafeUrl;
use uv_test::packse::scenario::{Package, PackageMetadata, Scenario};
use uv_test::packse::{PackseServer, generate_wheel};
use uv_test::{TestContext, uv_snapshot};

const FLASK_WHEEL: &str = "flask-3.0.0-py3-none-any.whl";

/// The local wheel depends on two packages that share a transitive dependency.
fn flask_wheel_fixture() -> Result<(TestContext, PackseServer)> {
    let context = uv_test::test_context!("3.12");
    let (filename, wheel) = generate_wheel(
        &"flask".parse()?,
        &"3.0.0".parse()?,
        &["jinja2==3.1.3".parse()?, "werkzeug==3.0.1".parse()?],
        &Default::default(),
        None,
        "py3-none-any",
        &[],
    );
    assert_eq!(filename, FLASK_WHEEL);
    context.temp_dir.child(filename).write_binary(&wheel)?;

    let mut scenario = Scenario::empty();
    for (name, version, requires) in [
        ("jinja2", "3.1.3", vec!["markupsafe==2.1.5".parse()?]),
        ("werkzeug", "3.0.1", vec!["markupsafe==2.1.5".parse()?]),
        ("markupsafe", "2.1.5", vec![]),
    ] {
        scenario.packages.insert(
            name.parse()?,
            Package {
                versions: [(
                    version.parse()?,
                    PackageMetadata {
                        requires,
                        ..PackageMetadata::wheel_only()
                    },
                )]
                .into(),
            },
        );
    }
    Ok((context, PackseServer::from_scenario(&scenario)))
}

#[test]
fn absolute_file_url() -> Result<()> {
    let (context, index) = flask_wheel_fixture()?;
    context
        .temp_dir
        .child("requirements.in")
        .write_str(&format!(
            "flask @ {}",
            SafeUrl::from_file_path(context.temp_dir.child(FLASK_WHEEL).path())
                .expect("absolute wheel path")
        ))?;
    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.in", "--index-url"])
        .arg(index.index_url()), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in
    flask @ file://[TEMP_DIR]/flask-3.0.0-py3-none-any.whl
        # via -r requirements.in
    jinja2==3.1.3
        # via flask
    markupsafe==2.1.5
        # via
        #   jinja2
        #   werkzeug
    werkzeug==3.0.1
        # via flask

    ----- stderr -----
    Resolved 4 packages in [TIME]
    ");
    Ok(())
}

