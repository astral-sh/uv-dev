//! Hash generation under artifact-selection policies.

use anyhow::Result;
use assert_fs::prelude::*;
use indoc::indoc;

use uv_static::EnvVars;
use uv_test::packse::{PackseServer, scenario::Scenario};
use uv_test::{TestContext, uv_snapshot};

fn setup() -> Result<(TestContext, PackseServer)> {
    let scenario = toml::from_str::<Scenario>(indoc! {r#"
        name = "artifact-hash-filtering"
        [root]
        [expected]
        satisfiable = true
        [packages.a.versions."1.0.0"]
        wheel_tags = ["py3-none-any", "py3-none-win_amd64"]
        [packages.b.versions."1.0.0"]
        [packages.c.versions."1.0.0"]
    "#})?;
    let server = PackseServer::from_scenario(&scenario);
    let context = uv_test::test_context!("3.12").with_filters(
        server
            .files()
            .map(|(filename, hash)| (hash.to_owned(), format!("[SHA256:{filename}]"))),
    );
    context
        .temp_dir
        .child("requirements.in")
        .write_str("a==1.0.0\nb==1.0.0\nc==1.0.0")?;
    Ok((context, server))
}

/// Apply per-package binary policies while retaining unrestricted and cross-platform hashes.
#[test]
fn generate_hashes_binary_package_overrides_preview() -> Result<()> {
    let (context, server) = setup()?;
    uv_snapshot!(context.filters(), context.pip_compile()
        .arg("requirements.in")
        .arg("--index-url").arg(server.index_url())
        .arg("--only-binary").arg("a")
        .arg("--no-binary").arg("b")
        .arg("--generate-hashes")
        .env(EnvVars::UV_PREVIEW_FEATURES, "artifact-hash-filtering"), @r"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --only-binary a --no-binary b --generate-hashes
    a==1.0.0 \
        --hash=sha256:[SHA256:a-1.0.0-py3-none-win_amd64.whl] \
        --hash=sha256:[SHA256:a-1.0.0-py3-none-any.whl]
        # via -r requirements.in
    b==1.0.0 \
        --hash=sha256:[SHA256:b-1.0.0.tar.gz]
        # via -r requirements.in
    c==1.0.0 \
        --hash=sha256:[SHA256:c-1.0.0.tar.gz] \
        --hash=sha256:[SHA256:c-1.0.0-py3-none-any.whl]
        # via -r requirements.in

    ----- stderr -----
    Resolved 3 packages in [TIME]
    ");
    Ok(())
}

/// A package-specific source requirement overrides a global wheels-only policy.
#[test]
fn package_policy_overrides_global() -> Result<()> {
    let (context, server) = setup()?;
    uv_snapshot!(context.filters(), context.pip_compile()
        .arg("requirements.in")
        .arg("--index-url").arg(server.index_url())
        .arg("--only-binary").arg(":all:")
        .arg("--no-binary").arg("b")
        .arg("--generate-hashes")
        .env(EnvVars::UV_PREVIEW_FEATURES, "artifact-hash-filtering"), @r"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --only-binary :all: --no-binary b --generate-hashes
    a==1.0.0 \
        --hash=sha256:[SHA256:a-1.0.0-py3-none-win_amd64.whl] \
        --hash=sha256:[SHA256:a-1.0.0-py3-none-any.whl]
        # via -r requirements.in
    b==1.0.0 \
        --hash=sha256:[SHA256:b-1.0.0.tar.gz]
        # via -r requirements.in
    c==1.0.0 \
        --hash=sha256:[SHA256:c-1.0.0-py3-none-any.whl]
        # via -r requirements.in

    ----- stderr -----
    Resolved 3 packages in [TIME]
    ");
    Ok(())
}
