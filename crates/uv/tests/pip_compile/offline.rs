//! Offline resolution from cached package metadata.

use anyhow::Result;
use assert_cmd::prelude::*;
use assert_fs::prelude::*;

use uv_test::packse::PackseServer;
use uv_test::packse::scenario::{Package, PackageMetadata, Scenario};
use uv_test::uv_snapshot;

/// A direct URL can be resolved offline only after its metadata is cached.
#[test]
fn offline_direct_url() -> Result<()> {
    let context = uv_test::test_context!("3.12");
    let mut scenario = Scenario::empty();
    scenario.packages.insert(
        "iniconfig".parse()?,
        Package {
            versions: [("2.0.0".parse()?, PackageMetadata::wheel_only())].into(),
        },
    );
    let server = PackseServer::from_scenario(&scenario);
    let wheel_url = server.file_url("iniconfig-2.0.0-py3-none-any.whl");
    context
        .temp_dir
        .child("requirements.in")
        .write_str(&format!("iniconfig @ {wheel_url}"))?;

    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.in", "--offline"]), @"
    exit_code: 1 (failure)
    ----- stderr -----
    error: Failed to download `iniconfig @ http://[LOCALHOST]/files/iniconfig-2.0.0-py3-none-any.whl`
      cause: Network connectivity is disabled, but the requested data wasn't found in the cache: http://[LOCALHOST]/files/iniconfig-2.0.0-py3-none-any.whl
    ");

    uv_snapshot!(context.filters(), context.pip_compile()
        .arg("requirements.in"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in
    iniconfig @ http://[LOCALHOST]/files/iniconfig-2.0.0-py3-none-any.whl
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");
    drop(server);

    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.in", "--offline"]), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --offline
    iniconfig @ http://[LOCALHOST]/files/iniconfig-2.0.0-py3-none-any.whl
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");
    Ok(())
}

/// Resolve a registry package and its transitive dependency offline only after caching metadata.
#[test]
fn offline_registry() -> Result<()> {
    let context = uv_test::test_context!("3.12");
    let mut scenario = Scenario::empty();
    for (name, requires) in [
        ("app", vec!["dependency==1.0.0".parse()?]),
        ("dependency", vec![]),
    ] {
        scenario.packages.insert(
            name.parse()?,
            Package {
                versions: [(
                    "1.0.0".parse()?,
                    PackageMetadata {
                        requires,
                        ..PackageMetadata::wheel_only()
                    },
                )]
                .into(),
            },
        );
    }
    let server = PackseServer::from_scenario(&scenario);
    let index_url = server.index_url();
    let requirements_in = context.temp_dir.child("requirements.in");
    requirements_in.write_str("app==1.0.0")?;

    // A reachable index cannot satisfy an offline request with an empty cache.
    uv_snapshot!(context.filters(), context.pip_compile()
        .arg("requirements.in")
        .arg("--offline")
        .arg("--index-url")
        .arg(&index_url), @"
    exit_code: 1 (failure)
    ----- stderr -----
    error: No solution found when resolving dependencies
      cause: Because app was not found in the cache and you require app==1.0.0, we can conclude that your requirements are unsatisfiable.

    hint: Packages were unavailable because the network was disabled. When the network is disabled, registry packages may only be read from the cache.
    ");

    context
        .pip_compile()
        .arg("requirements.in")
        .arg("--index-url")
        .arg(&index_url)
        .assert()
        .success();
    drop(server);

    uv_snapshot!(context.filters(), context.pip_compile()
        .arg("requirements.in")
        .arg("--offline")
        .arg("--index-url")
        .arg(&index_url), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --offline
    app==1.0.0
        # via -r requirements.in
    dependency==1.0.0
        # via app

    ----- stderr -----
    Resolved 2 packages in [TIME]
    ");

    Ok(())
}

/// Preserve package availability diagnostics for an explicit pre-release requirement.
#[test]
fn offline_registry_prerelease() -> Result<()> {
    let context = uv_test::test_context!("3.12");
    let requirements_in = context.temp_dir.child("requirements.in");
    requirements_in.write_str("flask==2.0.0rc1")?;

    uv_snapshot!(context.filters(), context.pip_compile()
            .arg("requirements.in")
            .arg("--offline"), @"
    exit_code: 1 (failure)
    ----- stderr -----
    error: No solution found when resolving dependencies
      cause: Because flask was not found in the cache and you require flask==2.0.0rc1, we can conclude that your requirements are unsatisfiable.

    hint: Packages were unavailable because the network was disabled. When the network is disabled, registry packages may only be read from the cache.
    ");

    Ok(())
}

/// Resolve a registry package without network access via the `--offline` flag. We should backtrack
/// to the latest version of the package that's available in the cache.
#[test]
fn offline_registry_backtrack() -> Result<()> {
    let context = uv_test::test_context!("3.12");
    let server = PackseServer::new("simple/single-package.toml");
    let index_url = server.index_url();
    let requirements_in = context.temp_dir.child("requirements.in");
    requirements_in.write_str("a==1.0.0")?;

    // Cache only the older version, while the cached index page also advertises `a==2.0.0`.
    context
        .pip_compile()
        .arg("requirements.in")
        .arg("--index-url")
        .arg(&index_url)
        .assert()
        .success();
    drop(server);

    requirements_in.write_str("a")?;

    uv_snapshot!(context.filters(), context.pip_compile()
        .arg("requirements.in")
        .arg("--index-url")
        .arg(index_url)
        .arg("--offline"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --offline
    a==1.0.0
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    "
    );

    Ok(())
}
