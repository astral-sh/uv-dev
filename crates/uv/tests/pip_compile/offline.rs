//! Offline resolution from cached package metadata.

use anyhow::Result;
use assert_fs::prelude::*;

use uv_test::packse::PackseServer;
use uv_test::packse::scenario::{Package, PackageMetadata, Scenario};
use uv_test::uv_snapshot;

/// A direct URL can be resolved offline only after its metadata is cached.
#[test]
fn offline_direct_url() -> Result<()> {
    let context = uv_test::test_context!("3.12");
    let mut scenario = Scenario::empty();
    scenario.packages.insert(
        "iniconfig".parse()?,
        Package {
            versions: [("2.0.0".parse()?, PackageMetadata::wheel_only())].into(),
        },
    );
    let server = PackseServer::from_scenario(&scenario);
    let wheel_url = server.file_url("iniconfig-2.0.0-py3-none-any.whl");
    context
        .temp_dir
        .child("requirements.in")
        .write_str(&format!("iniconfig @ {wheel_url}"))?;

    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.in", "--offline"]), @"
    exit_code: 1 (failure)
    ----- stderr -----
    error: Failed to download `iniconfig @ http://[LOCALHOST]/files/iniconfig-2.0.0-py3-none-any.whl`
      cause: Network connectivity is disabled, but the requested data wasn't found in the cache: http://[LOCALHOST]/files/iniconfig-2.0.0-py3-none-any.whl
    ");

    uv_snapshot!(context.filters(), context.pip_compile()
        .arg("requirements.in"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in
    iniconfig @ http://[LOCALHOST]/files/iniconfig-2.0.0-py3-none-any.whl
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");
    drop(server);

    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.in", "--offline"]), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --offline
    iniconfig @ http://[LOCALHOST]/files/iniconfig-2.0.0-py3-none-any.whl
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");
    Ok(())
}
