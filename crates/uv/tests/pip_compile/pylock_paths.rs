//! Archive paths in PEP 751 lockfiles are relative to the lockfile location.

use std::collections::BTreeMap;

use anyhow::Result;
use assert_fs::prelude::*;
use sha2::{Digest, Sha256};

use uv_test::archive::generate_source_archive;
use uv_test::packse::generate_wheel;
use uv_test::uv_snapshot;

#[test]
fn pep_751_compile_path_wheel() -> Result<()> {
    let context = uv_test::test_context!("3.12");
    let (filename, wheel) = generate_wheel(
        &"iniconfig".parse()?,
        &"2.0.0".parse()?,
        &[],
        &BTreeMap::new(),
        None,
        "py3-none-any",
        &[],
    );
    context.temp_dir.child(&filename).write_binary(&wheel)?;
    let context = context.with_filter((hex::encode(Sha256::digest(&wheel)), "[WHEEL_SHA256]"));
    context
        .temp_dir
        .child("requirements.txt")
        .write_str(&format!("./{filename}"))?;

    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.txt", "--universal", "-o", "pylock.toml"]), @r#"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.txt --universal -o pylock.toml
    lock-version = "1.0"
    created-by = "uv"
    requires-python = ">=3.12"

    [[packages]]
    name = "iniconfig"
    version = "2.0.0"
    archive = { path = "iniconfig-2.0.0-py3-none-any.whl", hashes = { sha256 = "[WHEEL_SHA256]" } }

    ----- stderr -----
    Resolved 1 package in [TIME]
    "#);
    uv_snapshot!(context.filters(), context.pip_sync().args(["--preview", "pylock.toml"]), @"
    exit_code: 0 (success)
    ----- stderr -----
    Installed 1 package in [TIME]
     + iniconfig==2.0.0 (from file://[TEMP_DIR]/iniconfig-2.0.0-py3-none-any.whl)
    ");
    context.assert_installed("iniconfig", "2.0.0");

    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.txt", "--universal", "-o", "nested/pylock.toml"]), @r#"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.txt --universal -o nested/pylock.toml
    lock-version = "1.0"
    created-by = "uv"
    requires-python = ">=3.12"

    [[packages]]
    name = "iniconfig"
    version = "2.0.0"
    archive = { path = "../iniconfig-2.0.0-py3-none-any.whl", hashes = { sha256 = "[WHEEL_SHA256]" } }

    ----- stderr -----
    Resolved 1 package in [TIME]
    "#);
    context.reset_venv();
    uv_snapshot!(context.filters(), context.pip_sync().args(["--preview", "nested/pylock.toml"]), @"
    exit_code: 0 (success)
    ----- stderr -----
    Installed 1 package in [TIME]
     + iniconfig==2.0.0 (from file://[TEMP_DIR]/iniconfig-2.0.0-py3-none-any.whl)
    ");
    context.assert_installed("iniconfig", "2.0.0");
    Ok(())
}

