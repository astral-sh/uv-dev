use uv_test::packse::scenario::Scenario;
use uv_test::uv_snapshot;

/// Universal resolution includes dependencies for earlier patches of the interpreter's minor version.
#[test]
#[cfg(feature = "test-universal")]
fn omit_python_patch_universal() -> Result<()> {
    let scenario: Scenario = toml::from_str(indoc! {r#"
        name = "universal-python-patch"
        [root]
        [expected]
        satisfiable = true
        [packages.redis.versions."5.0.3"]
        requires = ["async-timeout>=4.0.3; python_full_version < '3.11.3'"]
        requires_python = ">=3.7"
        sdist = false
        [packages.async-timeout.versions."4.0.3"]
        requires_python = ">=3.7"
        sdist = false
    "#})?;
    let index = PackseServer::from_scenario(&scenario);
    let context = uv_test::test_context!("3.11").with_env(EnvVars::UV_INDEX_URL, index.index_url());
    context
        .temp_dir
        .child("requirements.in")
        .write_str("redis")?;

    uv_snapshot!(context.pip_compile().arg("requirements.in"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in
    redis==5.0.3
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");

    // Context filters normalize interpreter patch versions, including the dependency's boundary.
    uv_snapshot!(context.pip_compile().args(["requirements.in", "--universal"]), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --universal
    async-timeout==4.0.3 ; python_full_version < '3.11.3'
        # via redis
    redis==5.0.3
        # via -r requirements.in

    ----- stderr -----
    Resolved 2 packages in [TIME]
    ");
    Ok(())
}

/// The emitted marker distinguishes platforms where a conditional requirement changes the output.
/// A requirement whose marker is false on the target platform still constrains the emitted marker,
/// since the resolved packages can differ on another platform.
#[test]
fn emit_marker_expression_conditional() -> Result<()> {
    let index = PackseServer::new("simple/single-package.toml");
    let context = uv_test::test_context!("3.12").with_env(EnvVars::UV_INDEX_URL, index.index_url());
    context
        .temp_dir
        .child("requirements.in")
        .write_str("a ; sys_platform == 'darwin'")?;
    let compile = |platform: &str| {
        let mut command = context.pip_compile();
        command.args([
            "requirements.in",
            "--python-platform",
            platform,
            "--emit-marker-expression",
        ]);
        command
    };

    uv_snapshot!(context.filters(), compile("linux"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --python-platform linux --emit-marker-expression
    # Pinned dependencies known to be valid for:
    #    sys_platform == 'linux'

    ----- stderr -----
    Resolved in [TIME]
    ");

    uv_snapshot!(context.filters(), compile("macos"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --python-platform macos --emit-marker-expression
    # Pinned dependencies known to be valid for:
    #    sys_platform == 'darwin'
    a==2.0.0
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");

    Ok(())
}
