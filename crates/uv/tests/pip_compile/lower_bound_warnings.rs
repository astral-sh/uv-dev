//! Lower-bound diagnostics and source overrides for project dependencies.

use std::io::Write;

use anyhow::Result;
use assert_fs::prelude::*;
use indoc::indoc;
use uv_static::EnvVars;
use uv_test::packse::{PackseServer, scenario::Scenario};
use uv_test::{TestContext, uv_snapshot};

const ANYIO_WHEEL: &str = "anyio-4.3.0-py3-none-any.whl";

struct Fixture {
    context: TestContext,
    index: PackseServer,
}

impl Fixture {
    fn new() -> Result<Self> {
        let scenario: Scenario = toml::from_str(indoc! {r#"
            name = "lower-bound-warnings"
            [root]
            [expected]
            satisfiable = true
            [packages.anyio.versions."4.3.0"]
            requires = ["idna>=2.8", "sniffio>=1.1"]
            sdist = false
            [packages.idna.versions."3.6"]
            sdist = false
            [packages.sniffio.versions."1.3.1"]
            sdist = false
            [packages.tqdm.versions."4.66.2"]
            sdist = false
        "#})?;
        let index = PackseServer::from_scenario(&scenario);
        let context = uv_test::test_context!("3.12")
            .with_env(EnvVars::UV_INDEX_URL, index.index_url())
            .with_filter((
                index.file_url(ANYIO_WHEEL),
                format!("http://[LOCALHOST]/files/{ANYIO_WHEEL}"),
            ));
        context
            .temp_dir
            .child("pyproject.toml")
            .write_str(indoc! {r#"
            [project]
            name = "foo"
            version = "0.0.0"
            dependencies = ["tqdm", "anyio==4.3.0"]
        "#})?;
        Ok(Self { context, index })
    }

    fn add_source(&self) -> Result<()> {
        let mut project = fs_err::OpenOptions::new()
            .append(true)
            .open(self.context.temp_dir.join("pyproject.toml"))?;
        writeln!(
            project,
            "\n[tool.uv.sources]\nanyio = {{ url = \"{}\" }}",
            self.index.file_url(ANYIO_WHEEL)
        )?;
        Ok(())
    }
}

#[test]
fn default_resolution_with_source_override_does_not_warn() -> Result<()> {
    let fixture = Fixture::new()?;
    fixture.add_source()?;
    uv_snapshot!(fixture.context.filters(), fixture.context.pip_compile().arg("pyproject.toml"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] pyproject.toml
    anyio @ http://[LOCALHOST]/files/anyio-4.3.0-py3-none-any.whl
        # via foo (pyproject.toml)
    idna==3.6
        # via anyio
    sniffio==1.3.1
        # via anyio
    tqdm==4.66.2
        # via foo (pyproject.toml)

    ----- stderr -----
    Resolved 4 packages in [TIME]
    ");
    Ok(())
}

