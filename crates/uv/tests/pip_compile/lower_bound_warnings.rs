#[test]
fn lowest_resolution_with_source_override_warns() -> Result<()> {
    let fixture = Fixture::new()?;
    fixture.add_source()?;
    uv_snapshot!(fixture.context.filters(), fixture.context.pip_compile()
        .args(["pyproject.toml", "--resolution", "lowest"]), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] pyproject.toml --resolution lowest
    anyio @ http://[LOCALHOST]/files/anyio-4.3.0-py3-none-any.whl
        # via foo (pyproject.toml)
    idna==3.6
        # via anyio
    sniffio==1.3.1
        # via anyio
    tqdm==4.66.2
        # via foo (pyproject.toml)

    ----- stderr -----
    warning: The direct dependency `tqdm` is unpinned. Consider setting a lower bound when using `--resolution lowest` or `--resolution lowest-direct` to avoid using outdated versions.
    Resolved 4 packages in [TIME]
    ");
    Ok(())
}
