//! Remote find-links inputs and artifact hashes.

use anyhow::Result;
use assert_fs::prelude::*;
use sha2::{Digest, Sha256};

use uv_static::EnvVars;
use uv_test::find_links::FindLinksServer;
use uv_test::packse::generate_wheel;
use uv_test::{TestContext, uv_snapshot};

fn setup() -> Result<(TestContext, FindLinksServer)> {
    let context = uv_test::test_context!("3.12");
    let (filename, wheel) = generate_wheel(
        &"tqdm".parse()?,
        &"4.64.1".parse()?,
        &[],
        &Default::default(),
        None,
        "py3-none-any",
        &[],
    );
    let wheelhouse = context.temp_dir.child("wheelhouse");
    wheelhouse.child(&filename).write_binary(&wheel)?;
    let hash = hex::encode(Sha256::digest(&wheel));
    let context = context.with_filter((format!("sha256:{hash}"), "sha256:[TQDM_WHEEL_SHA256]"));
    let server = FindLinksServer::new(wheelhouse.path());
    Ok((context, server))
}

/// Hash the wheel served by a remote HTML find-links page.
#[test]
fn generate_hashes_find_links_url() -> Result<()> {
    let (context, server) = setup()?;
    context
        .temp_dir
        .child("requirements.in")
        .write_str("tqdm")?;
    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.in", "--generate-hashes", "--no-index", "--find-links"])
        .arg(server.url()), @r"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --generate-hashes --no-index
    tqdm==4.64.1 \
        --hash=sha256:[TQDM_WHEEL_SHA256]
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");
    Ok(())
}

/// Expand an environment variable within a requirements-file find-links directive.
#[test]
fn find_links_env_var() -> Result<()> {
    let (context, server) = setup()?;
    context
        .temp_dir
        .child("requirements.in")
        .write_str("tqdm\n--find-links ${URL}")?;
    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.in", "--no-index"])
        .env(EnvVars::URL, server.url()), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --no-index
    tqdm==4.64.1
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");
    Ok(())
}

/// Re-emit a requirements-file find-links source alongside the resolved package.
#[test]
fn find_links_requirements_txt() -> Result<()> {
    let (context, server) = setup()?;
    context
        .temp_dir
        .child("requirements.in")
        .write_str(&format!("-f {}/\ntqdm", server.url()))?;
    uv_snapshot!(context.filters(), context.pip_compile()
        .args(["requirements.in", "--no-index", "--emit-find-links"]), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --no-index --emit-find-links
    --find-links http://[LOCALHOST]/

    tqdm==4.64.1
        # via -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");
    Ok(())
}

