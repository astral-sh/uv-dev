use std::os::unix::fs::FileTypeExt;
use std::path::Path;
use std::thread;
use std::time::Duration;

use anyhow::Result;
use assert_cmd::prelude::*;
use assert_fs::prelude::*;
use indoc::formatdoc;
use uv_static::EnvVars;
use uv_test::packse::PackseServer;
use uv_test::{DEFAULT_PYTHON_VERSION, TestContext, apply_filters, assert_link_target};

const TIMEOUT: Duration = Duration::from_secs(60);

fn setup() -> Result<(TestContext, PackseServer)> {
    let index = PackseServer::new("simple/single-package.toml");
    let context = uv_test::test_context!(DEFAULT_PYTHON_VERSION)
        .with_env(EnvVars::UV_INDEX_URL, index.index_url());
    context
        .temp_dir
        .child("requirements.in")
        .write_str("a==1.0.0")?;
    Ok((context, index))
}

fn mkfifo(context: &TestContext, path: &Path) {
    context
        .python_command()
        .args(["-c", "import os, sys; os.mkfifo(sys.argv[1])"])
        .arg(path)
        .assert()
        .success();
}

fn compile(context: &TestContext, destination: &str) -> Result<Vec<u8>> {
    let mut command = context.pip_compile();
    command.args(["requirements.in", "--output-file", destination]);
    let result = assert_cmd::Command::from_std(command)
        .timeout(TIMEOUT)
        .assert()
        .success();
    let output = result.get_output();
    assert_eq!(
        apply_filters(String::from_utf8(output.stdout.clone())?, context.filters()),
        formatdoc! {"
            # This file was autogenerated by uv via the following command:
            #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --output-file {destination}
            a==1.0.0
                # via -r requirements.in
        "}
    );
    assert_eq!(
        apply_filters(String::from_utf8(output.stderr.clone())?, context.filters()),
        "Resolved 1 package in [TIME]\n"
    );
    Ok(output.stdout.clone())
}

fn assert_fifo_output(context: &TestContext, fifo: &Path, destination: &str) -> Result<()> {
    let mut reader = context.python_command();
    reader
        .args([
            "-c",
            "import pathlib, sys; sys.stdout.buffer.write(pathlib.Path(sys.argv[1]).read_bytes())",
        ])
        .arg(fifo);
    thread::scope(|scope| {
        // A separate process lets the timeout terminate a reader blocked in open or read.
        let reader = scope.spawn(move || {
            assert_cmd::Command::from_std(reader)
                .timeout(TIMEOUT)
                .assert()
                .success()
                .get_output()
                .stdout
                .clone()
        });
        let output = compile(context, destination)?;
        assert_eq!(reader.join().expect("FIFO reader panicked"), output);
        Ok(())
    })
}

/// A FIFO is an output stream, not a source of pinned versions or a file to replace.
#[test]
fn fifo() -> Result<()> {
    let (context, _index) = setup()?;
    let output = context.temp_dir.child("requirements.txt");
    mkfifo(&context, output.path());
    assert_fifo_output(&context, output.path(), "requirements.txt")?;
    assert!(fs_err::metadata(output.path())?.file_type().is_fifo());
    Ok(())
}

/// Detect special destinations through relative symlinks before resolving the output path.
#[test]
fn symlink_to_fifo() -> Result<()> {
    let (context, _index) = setup()?;
    let fifo = context.temp_dir.child("output.fifo");
    mkfifo(&context, fifo.path());
    let output = context.temp_dir.child("requirements.txt");
    output.symlink_to_file("output.fifo")?;
    assert_fifo_output(&context, fifo.path(), "requirements.txt")?;
    assert_link_target(output, "output.fifo");
    assert!(fs_err::metadata(fifo.path())?.file_type().is_fifo());
    Ok(())
}

/// Resolve the link's target relative to its parent, preserving an unrelated FIFO in the cwd.
#[test]
fn nested_relative_symlink() -> Result<()> {
    let (context, _index) = setup()?;
    let target = context.temp_dir.child("nested/requirements.txt");
    target.write_str("")?;
    let output = context.temp_dir.child("nested/output.txt");
    output.symlink_to_file("requirements.txt")?;
    let unrelated_fifo = context.temp_dir.child("requirements.txt");
    mkfifo(&context, unrelated_fifo.path());

    let stdout = compile(&context, "nested/output.txt")?;
    assert_link_target(output, "requirements.txt");
    assert!(
        fs_err::metadata(unrelated_fifo.path())?
            .file_type()
            .is_fifo()
    );
    assert_eq!(fs_err::read(target.path())?, stdout);
    Ok(())
}
