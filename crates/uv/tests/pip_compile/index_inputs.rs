use anyhow::Result;
use assert_fs::prelude::*;

use uv_test::packse::PackseServer;
use uv_test::uv_snapshot;

/// A repeated index URL in requirements and constraints still supplies the constrained package.
#[test]
fn matching_index_urls_requirements_txt() -> Result<()> {
    let context = uv_test::test_context!("3.12");
    let index = PackseServer::new("simple/single-package.toml");
    let index_url = index.index_url();
    context
        .temp_dir
        .child("requirements.in")
        .write_str(&format!("--index-url {index_url}\na>=1\n"))?;
    context
        .temp_dir
        .child("constraints.in")
        .write_str(&format!("--index-url {index_url}\na<2\n"))?;

    uv_snapshot!(context.filters(), context.pip_compile()
        .arg("requirements.in")
        .arg("--constraint")
        .arg("constraints.in"), @"
    exit_code: 0 (success)
    ----- stdout -----
    # This file was autogenerated by uv via the following command:
    #    uv pip compile --cache-dir [CACHE_DIR] requirements.in --constraint constraints.in
    a==1.0.0
        # via
        #   -c constraints.in
        #   -r requirements.in

    ----- stderr -----
    Resolved 1 package in [TIME]
    ");

    Ok(())
}
